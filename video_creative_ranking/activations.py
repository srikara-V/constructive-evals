"""Prepend VLM output tokens (+ audio transcript) to an open-source LLM
context and extract pooled hidden states at every layer.

The LLM never sees pixels: its entire knowledge of the video is the VLM's
generated tokens plus the Whisper transcript, exactly the setup requested
for creative-ranking-videos-2. The trailing question focuses the final
token positions on a performance judgment, which is where contrastive
vectors tend to be most linearly readable.

For each creative we cache a tensor of shape [n_layers+1, 3, hidden]:
  pooling 0 = mean over the whole context
  pooling 1 = mean over the last 32 tokens (the judgment region)
  pooling 2 = last token
plus a zero-shot judge score logP("Yes") - logP("No") from the same pass.
"""

import hashlib
import json
import re
from pathlib import Path

import torch

CONTEXT_TEMPLATE = """Video ad creative analysis.

[VIDEO — visual description generated by a vision-language model]
{caption}

[AUDIO — transcript of the soundtrack]
{transcript}

[TASK]
The material above fully describes one short-form video advertisement{brand_clause}. \
Consider its hook strength, visual clarity, emotional appeal, pacing, on-screen text, \
and call-to-action. Question: will this ad achieve a high click-through rate compared \
to other ads for the same product? Answer (Yes or No):"""

LAST_K = 32  # pooling window for the "judgment region"


def _slug(name: str) -> str:
    return re.sub(r"[^a-zA-Z0-9]+", "-", name).strip("-").lower()


def build_context(caption: str, transcript: str, creative) -> str:
    brand = creative.meta.get("brand") or creative.meta.get("advertiser")
    brand_clause = f" for {brand}" if brand else ""
    return CONTEXT_TEMPLATE.format(
        caption=caption.strip() or "(no visual description available)",
        transcript=transcript.strip() or "(no speech detected)",
        brand_clause=brand_clause,
    )


class ActivationExtractor:
    def __init__(self, cfg):
        from transformers import AutoModelForCausalLM, AutoTokenizer
        from .captioner import _from_pretrained_kwargs

        self.cfg = cfg
        self.device = cfg.resolved_device()
        dtype = cfg.torch_dtype()
        print(f"Loading LLM {cfg.llm_model} ({self.device}, {dtype})...")
        self.tokenizer = AutoTokenizer.from_pretrained(cfg.llm_model)
        # over-long contexts must lose caption text, never the trailing
        # question that the last-token/last-32 poolings depend on
        self.tokenizer.truncation_side = "left"
        self.model = AutoModelForCausalLM.from_pretrained(
            cfg.llm_model, **_from_pretrained_kwargs(dtype, self.device)
        )
        if self.device != "cuda":
            self.model = self.model.to(self.device)
        self.model.eval()

        cfg_m = self.model.config
        text_cfg = getattr(cfg_m, "text_config", cfg_m)
        self.n_layers = text_cfg.num_hidden_layers
        self.hidden_size = text_cfg.hidden_size
        print(f"  Layers: {self.n_layers}, Hidden: {self.hidden_size}")

        self.yes_ids, self.no_ids = self._answer_token_ids()

    def _answer_token_ids(self):
        """First-token ids for Yes/No answers, with/without leading space."""
        def first_ids(words):
            ids = set()
            for w in words:
                toks = self.tokenizer.encode(w, add_special_tokens=False)
                if toks:
                    ids.add(toks[0])
            return sorted(ids)
        return first_ids(["Yes", " Yes", "yes", " yes"]), \
               first_ids(["No", " No", "no", " no"])

    def _format(self, context: str) -> str:
        if self.cfg.use_chat_template and self.tokenizer.chat_template:
            return self.tokenizer.apply_chat_template(
                [{"role": "user", "content": context}],
                tokenize=False, add_generation_prompt=True)
        return context

    @torch.no_grad()
    def extract(self, context: str) -> tuple[torch.Tensor, float]:
        """Returns (pooled [n_layers+1, 3, hidden], judge_score)."""
        text = self._format(context)
        enc = self.tokenizer(text, return_tensors="pt", truncation=True,
                             max_length=self.cfg.max_context_tokens)
        enc = {k: v.to(self.model.device) for k, v in enc.items()}
        outputs = self.model(**enc, output_hidden_states=True, return_dict=True)

        pooled = []
        for h in outputs.hidden_states:  # embeddings + each layer
            h = h[0].float()  # [seq, hidden]
            pooled.append(torch.stack([
                h.mean(0),
                h[-LAST_K:].mean(0),
                h[-1],
            ]))
        pooled = torch.stack(pooled).to(torch.float16).cpu()

        logprobs = torch.log_softmax(outputs.logits[0, -1].float(), dim=-1)
        judge = (torch.logsumexp(logprobs[self.yes_ids], 0)
                 - torch.logsumexp(logprobs[self.no_ids], 0)).item()
        return pooled, judge


def extract_activations(creatives, captions, transcripts, cfg):
    """Cached per-layer pooled activations for every creative.

    Returns ({creative_id: tensor [n_layers+1, 3, hidden]},
             {creative_id: judge_score}).
    """
    from .data import video_cache_key

    cache_dir = Path(cfg.cache_dir) / "activations"
    cache_dir.mkdir(parents=True, exist_ok=True)
    audio_tag = "aud" if cfg.use_audio else "noaud"
    chat_tag = "chat" if cfg.use_chat_template else "raw"
    tmpl_hash = hashlib.sha1(CONTEXT_TEMPLATE.encode()).hexdigest()[:8]

    extractor = None
    acts: dict[str, torch.Tensor] = {}
    judges: dict[str, float] = {}
    from tqdm import tqdm
    for c in tqdm(creatives, desc="LLM activations"):
        context = build_context(captions[c.id]["caption"], transcripts[c.id], c)
        ctx_hash = hashlib.sha1(context.encode()).hexdigest()[:10]
        tag = f"{_slug(cfg.llm_model)}_{audio_tag}_{chat_tag}_{tmpl_hash}"
        pt_file = cache_dir / f"{video_cache_key(c)}_{tag}_{ctx_hash}.pt"
        if pt_file.exists():
            blob = torch.load(pt_file, weights_only=True)
            acts[c.id], judges[c.id] = blob["pooled"], blob["judge"]
            continue
        if extractor is None:
            extractor = ActivationExtractor(cfg)
        pooled, judge = extractor.extract(context)
        torch.save({"pooled": pooled, "judge": judge}, pt_file)
        acts[c.id], judges[c.id] = pooled, judge
    return acts, judges
