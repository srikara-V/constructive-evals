"""Order-debiased pairwise LLM judge over the prepended video contexts.

Both creatives' VLM descriptions (+ transcripts) go into one prompt asking
"which ad will get the higher CTR?", and the judgment is read from the
logits as logP("A") - logP("B") — soft scores, not argmax (G-Eval,
arXiv:2303.16634; GenRM, arXiv:2408.15240). Because LLM judges flip on
~1/3 of order swaps (arXiv:2306.05685, arXiv:2305.17926), every pair is
judged in BOTH orders and the margins are averaged.

Zero training required, so this is the honest floor any trained method
(v2 contrastive, v3 probes, v4 VLM-native) has to beat.
"""

import hashlib
import json
import re
from pathlib import Path

import torch

PAIR_TEMPLATE = """Two short-form video advertisements for the same product are described below. \
Each description was generated by a vision-language model from the video, followed by the \
audio transcript.

=== AD {first} ===
{ctx_first}

=== AD {second} ===
{ctx_second}

Question: Which ad will achieve the higher click-through rate? Consider hook strength, \
visual clarity, emotional appeal, pacing, on-screen text, and call-to-action. \
Answer with a single letter, {first} or {second}. Answer:"""


def _creative_block(caption: str, transcript: str) -> str:
    t = transcript.strip() or "(no speech detected)"
    return f"[VIDEO] {caption.strip()}\n[AUDIO] {t}"


class PairwiseJudge:
    def __init__(self, cfg):
        from transformers import AutoModelForCausalLM, AutoTokenizer
        from .captioner import _from_pretrained_kwargs

        self.cfg = cfg
        self.device = cfg.resolved_device()
        print(f"Loading LLM {cfg.llm_model} for pairwise judging...")
        self.tokenizer = AutoTokenizer.from_pretrained(cfg.llm_model)
        # keep the trailing "Answer:" when a pair overflows the window
        self.tokenizer.truncation_side = "left"
        self.model = AutoModelForCausalLM.from_pretrained(
            cfg.llm_model, **_from_pretrained_kwargs(cfg.torch_dtype(), self.device)
        )
        if self.device != "cuda":
            self.model = self.model.to(self.device)
        self.model.eval()
        self.a_ids = self._first_ids(["A", " A"])
        self.b_ids = self._first_ids(["B", " B"])

    def _first_ids(self, words):
        ids = set()
        for w in words:
            toks = self.tokenizer.encode(w, add_special_tokens=False)
            if toks:
                ids.add(toks[0])
        return sorted(ids)

    def _format(self, prompt: str) -> str:
        if self.cfg.use_chat_template and self.tokenizer.chat_template:
            return self.tokenizer.apply_chat_template(
                [{"role": "user", "content": prompt}],
                tokenize=False, add_generation_prompt=True)
        return prompt

    @torch.no_grad()
    def _margin(self, ctx_first: str, ctx_second: str) -> float:
        """logP(first wins) - logP(second wins), letters fixed as A=first."""
        prompt = PAIR_TEMPLATE.format(first="A", second="B",
                                      ctx_first=ctx_first, ctx_second=ctx_second)
        text = self._format(prompt)
        enc = self.tokenizer(text, return_tensors="pt", truncation=True,
                             max_length=2 * self.cfg.max_context_tokens)
        enc = {k: v.to(self.model.device) for k, v in enc.items()}
        logits = self.model(**enc).logits[0, -1].float()
        logprobs = torch.log_softmax(logits, dim=-1)
        return (torch.logsumexp(logprobs[self.a_ids], 0)
                - torch.logsumexp(logprobs[self.b_ids], 0)).item()

    def judge(self, ctx_a: str, ctx_b: str) -> float:
        """Order-debiased margin > 0 means creative A is predicted to win."""
        m_ab = self._margin(ctx_a, ctx_b)        # A shown first
        m_ba = self._margin(ctx_b, ctx_a)        # B shown first
        return 0.5 * (m_ab - m_ba)


def judge_pairs(pairs, captions, transcripts, cfg) -> list[float]:
    """Cached order-debiased margins for a list of pairs (aligned order)."""
    cache_dir = Path(cfg.cache_dir) / "pairwise_judge"
    cache_dir.mkdir(parents=True, exist_ok=True)
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", cfg.llm_model).strip("-").lower()
    tmpl_hash = hashlib.sha1(PAIR_TEMPLATE.encode()).hexdigest()[:8]

    judge = None
    margins = []
    from tqdm import tqdm
    for p in tqdm(pairs, desc="Pairwise judging (both orders)"):
        ctx_a = _creative_block(captions[p.creative_a.id]["caption"],
                                transcripts[p.creative_a.id])
        ctx_b = _creative_block(captions[p.creative_b.id]["caption"],
                                transcripts[p.creative_b.id])
        key = hashlib.sha1(f"{ctx_a}||{ctx_b}".encode()).hexdigest()[:16]
        cache_file = cache_dir / f"{key}_{slug}_{tmpl_hash}.json"
        if cache_file.exists():
            with open(cache_file) as f:
                margins.append(json.load(f)["margin"])
            continue
        if judge is None:
            judge = PairwiseJudge(cfg)
        m = judge.judge(ctx_a, ctx_b)
        with open(cache_file, "w") as f:
            json.dump({"margin": m}, f)
        margins.append(m)
    return margins
